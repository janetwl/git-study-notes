def set_paras(shape, lines):
    tf = shape.text_frame
    paras = tf.paragraphs
    if len(paras) < len(lines):          # 极少需要:补段
        while len(tf.paragraphs) < len(lines):
            tf.add_paragraph()
        paras = tf.paragraphs
    n = 0
    for p in paras:
        txt = lines[n] if n < len(lines) else None
        if txt is not None:
            target = None
            for r in p.runs:
                if r.text.strip() and target is None:
                    target = r
                elif r is not target:
                    r.text = ""
            if target is not None:
                target.text = txt
            else:
                if p.runs: p.runs[0].text = txt
                else: p.text = txt
        n += 1
    # 多余的段落清空
    for p in paras[len(lines):]:
        for r in p.runs: r.text = ""

prs = Presentation(SRC)
done, miss = 0, []
for idx, slide in enumerate(prs.slides, 1):
    names = {sh.name: sh for sh in slide.shapes}
    for (sn, name), lines in list(M.items()):
        if sn == idx and name in names:
            sh = names[name]
            if sh.has_text_frame:
                set_paras(sh, lines); done += 1; del M[(sn, name)]
print("replaced:", done)
print("missing:", sorted(miss) if miss else "none")
